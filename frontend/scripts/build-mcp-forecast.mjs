import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const template = new URL('../mcp-ui/forecast_chart.html', import.meta.url);
const target = new URL('../../backend/app/mcp_ui/forecast_chart_v2.html', import.meta.url);
const bundle = await build({
  configFile: false,
  publicDir: false,
  build: {
    write: false,
    license: { fileName: 'licenses.md' },
    target: 'es2020',
    minify: true,
    lib: {
      entry: fileURLToPath(new URL('../mcp-ui/forecast_chart.js', import.meta.url)),
      formats: ['iife'],
      name: 'ParraGlideatorForecast',
    },
  },
});
const { output } = bundle[0];
const script = output.find((item) => item.type === 'chunk' && item.isEntry).code;
const licenses = output.find((item) => item.fileName === 'licenses.md').source;
// Keep the widget self-contained in the backend's separate Render deployment.
const inlineScript = `/*\n${licenses.replaceAll('*/', '* /')}\n*/\n${script}`.replace(/<\/script/gi, '<\\/script');
const source = await readFile(template, 'utf8');
const artifact = '<!-- Generated by npm run build:mcp-forecast in frontend. -->\n'
  + source.replace('<!-- WIDGET_SCRIPT -->', () => `<script>\n${inlineScript}</script>`);

if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== artifact) {
    console.error('The MCP forecast widget is out of date. Run npm run build:mcp-forecast in frontend.');
    process.exitCode = 1;
  }
} else {
  await writeFile(target, artifact);
}
