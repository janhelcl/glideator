import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const [chart, ...options] = process.argv.slice(2);
const targets = {
  forecast: { source: 'forecast_chart', target: 'forecast_chart_v2.html' },
  seasonality: { source: 'seasonality_chart', target: 'seasonality_chart_v1.html' },
  map: { source: 'forecast_map', target: 'forecast_map_v1.html' },
};
if (!Object.hasOwn(targets, chart)) {
  throw new Error('Specify forecast, seasonality, or map to build an MCP widget.');
}
const widget = targets[chart];
const template = new URL(`../mcp-ui/${widget.source}.html`, import.meta.url);
const target = new URL(`../../backend/app/mcp_ui/${widget.target}`, import.meta.url);
const bundle = await build({
  configFile: false,
  publicDir: false,
  build: {
    write: false,
    license: { fileName: 'licenses.md' },
    target: 'es2020',
    minify: true,
    lib: {
      entry: fileURLToPath(new URL(`../mcp-ui/${widget.source}.js`, import.meta.url)),
      formats: ['iife'],
      name: 'ParraGlideatorChart',
    },
  },
});
const { output } = bundle[0];
const script = output.find((item) => item.type === 'chunk' && item.isEntry).code;
const licenses = output.find((item) => item.fileName === 'licenses.md').source.replaceAll('\r\n', '\n');
const styles = output.filter((item) => item.type === 'asset' && item.fileName.endsWith('.css'))
  .map((item) => item.source).join('\n');
// Keep the widget self-contained in the backend's separate Render deployment.
const inlineScript = `/*\n${licenses.replaceAll('*/', '* /')}\n*/\n${script}`.replace(/<\/script/gi, '<\\/script');
const source = await readFile(template, 'utf8');
const artifact = `<!-- Generated by npm run build:mcp-${chart} in frontend. -->\n`
  + source
    .replace('<!-- WIDGET_STYLE -->', () => `<style>\n${styles}</style>`)
    .replace('<!-- WIDGET_SCRIPT -->', () => `<script>\n${inlineScript}</script>`);

if (options.includes('--check')) {
  if (await readFile(target, 'utf8') !== artifact) {
    console.error(`The MCP ${chart} widget is out of date. Run npm run build:mcp-${chart} in frontend.`);
    process.exitCode = 1;
  }
} else {
  await writeFile(target, artifact);
}
